//! Update logic over bytes: no network, no UI (`docs/ARCHITECTURE.md` section 11).
//!
//! The order a caller follows, each step a pure function here:
//!
//! 1. [`check_update`]: parse the GitHub Releases JSON, pick the assets, compare versions.
//! 2. Download `manifest.json`, `manifest.json.sig` and the zip (the fetch is not written yet).
//! 3. [`verify_manifest`]: the signature over the exact manifest bytes, against the embedded public key.
//! 4. [`verify_zip`]: the zip's SHA-256 against the signed manifest.
//! 5. [`plan_swap`] then [`stage`] then [`apply`]: extract next to the exe, retire the current files as `.old`,
//!    move the new ones in, roll back on failure. Nothing outside the install folder is ever touched.

